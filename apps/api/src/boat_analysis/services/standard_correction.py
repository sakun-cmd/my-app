def get_correction(venue_code: str | None, lane: int, metric: str) -> Decimal:
    """指定した場・艇・タイム項目のスタンダード版補正値(秒)を返す。

    未知の場・艇・項目の場合は0.00(補正なし)を返す。
    """
    if venue_code is None:
        return _D("0.00")
    return STANDARD_CORRECTION_SECONDS.get(venue_code, {}).get(lane, {}).get(metric, _D("0.00"))
